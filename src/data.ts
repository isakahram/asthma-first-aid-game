export function getScore(answers: number[]) {
  return answers.reduce((sum, answer, index) => sum + (scenarios[index]?.options[answer]?.points ?? 0), 0)
}

export function getScoreRange(score: number) {
  return scoreRanges.find((range) => score >= range.min && score <= range.max) ?? scoreRanges[0]
}
